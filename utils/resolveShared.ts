/** The client media ID is only a lookup key, never authorization. */
export interface SharedMapping { id:string; owner_id:string; post_id:string|null; object_path:string; state:string; sha256:string; slot:number|null; }
export interface VisiblePost {id:string;user_id:string;is_public:boolean;audience:string|null;section:string|null;progress_stats:unknown;}
export interface SharedDependencies {
 findMapping(id:string):Promise<SharedMapping|null>;
 // Must use viewer JWT, never service-role query. Current RLS enforces blocks.
 findVisiblePost(id:string):Promise<VisiblePost|null>;
 canViewProfile(owner:string):Promise<boolean>;
 canAccessClub(actor:string):Promise<boolean>;
}
const UUID=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
export function sharedReference(id:unknown):string|null {return typeof id==='string'&&UUID.test(id)?`macrogoal-private-photo:shared/${id}`:null;}
export function createSharedResolver(deps:SharedDependencies){return async(actor:string,id:string)=>{
 if(!UUID.test(actor)||!UUID.test(id))return null;
 const m=await deps.findMapping(id);
 if(!m||m.id!==id||m.state!=='bound'||!m.post_id||!UUID.test(m.owner_id)||!UUID.test(m.post_id)||!Number.isInteger(m.slot)||m.slot!<0||m.slot!>3||! /^[a-f0-9]{64}$/.test(m.sha256))return null;
 // Object keys generated by server; no arbitrary bucket, traversal or source path.
 if(m.object_path!==`${m.owner_id}/${m.id}`)return null;
 const p=await deps.findVisiblePost(m.post_id);
 if(!p||p.id!==m.post_id||p.user_id!==m.owner_id)return null;
 if(p.section!=='feed'&&p.section!=='club')return null;
 if(p.section==='club'&&actor!==m.owner_id&&!await deps.canAccessClub(actor))return null;
 if(p.audience!==null&&p.audience!=='public'&&p.audience!=='followers')return null;
 if(actor!==m.owner_id){
  if(p.is_public!==true)return null;
  if(p.audience==='followers'&&!await deps.canViewProfile(m.owner_id))return null;
 }
 const stats=p.progress_stats as {photo_progress?:Array<{media_id?:unknown}>}|null;
 if(!stats||!Array.isArray(stats.photo_progress)||stats.photo_progress.length>4||stats.photo_progress[m.slot!]?.media_id!==m.id)return null;
 return {bucket:'community-progress-media',path:m.object_path,binding:`${m.id}:${m.post_id}:${m.slot}:${m.sha256}`};
};}
