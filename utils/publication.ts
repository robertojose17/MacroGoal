/** In-memory single-composer publication checkpoint. No URLs/bytes stored in post. */
export type CapturedPhoto={sourceId:string;uri:string;date:string;weight:number|null;weight_unit:string|null};
export type SharedSlot={media_id:string;date:string;weight:number|null;weight_unit:string|null};
export type PublicationCheckpoint<T>={actor:string;generation:number;intent:string;postId:string|null;sources:Array<{id:string;key:string}>;slots:SharedSlot[];post?:T;busy:boolean;};
export interface PublicationDeps<T>{intent:string;actor:()=>Promise<{id:string;generation:number}>;correlationKey:()=>string;upload:(source:string,uri:string,key:string)=>Promise<string>;create:(id:string,slots:SharedSlot[])=>Promise<T>;bind:(id:string,ids:string[])=>Promise<void>;}
export async function publishProgress<T>(photos:CapturedPhoto[],deps:PublicationDeps<T>,checkpoint:{current:PublicationCheckpoint<T>|null}):Promise<T>{
 const actor=await deps.actor();let cp=checkpoint.current;
 if(cp&&cp.actor!==actor.id)throw Error('Session changed');
 // Between attempts, a freshly authenticated SAME owner may resume stable IDs.
 // No bytes/tokens are retained in checkpoint; every bind revalidates server ownership.
 // In-flight generation changes still abort below; never carry state across actors.
 if(cp&&cp.generation!==actor.generation){if(cp.busy)throw Error('Session changed');cp.generation=actor.generation;}
 if(cp&&cp.intent!==deps.intent)throw Error('PUBLICATION_CHANGED');
 const assert=async()=>{const a=await deps.actor();if(a.id!==actor.id||a.generation!==actor.generation)throw Error('Session changed');};
 if(!cp){
  if(photos.length<1||photos.length>4||new Set(photos.map(p=>p.sourceId)).size!==photos.length)throw Error('Invalid selection');
  cp={actor:actor.id,generation:actor.generation,intent:deps.intent,postId:null,sources:photos.map(p=>({id:p.sourceId,key:deps.correlationKey()})),slots:[],busy:false};
  checkpoint.current=cp;
 }
 if(cp.busy)throw Error('Publication in progress');
 cp.busy=true;
 try{
  // Checkpoint keys survive partial upload. Retry uses same source/key; never overwrites.
  for(let i=cp.slots.length;i<cp.sources.length;i++){
   const source=cp.sources[i];const p=photos.find(p=>p.sourceId===source.id);if(!p)throw Error('Capture required');
   await assert();const id=await deps.upload(source.id,p.uri,source.key);await assert();cp.slots.push({media_id:id,date:p.date,weight:p.weight,weight_unit:p.weight_unit});
  }
  // First media UUID is generated by Postgres, not client randomness.
  cp.postId ??= cp.slots[0].media_id;
  // create is an idempotent insert/read by this stable ID, never an upsert.
  if(!cp.post){await assert();cp.post=await deps.create(cp.postId,cp.slots);}
  await assert();await deps.bind(cp.postId,cp.slots.map(p=>p.media_id));await assert();return cp.post;
 }finally{cp.busy=false;}
}
